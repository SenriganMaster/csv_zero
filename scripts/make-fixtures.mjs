/**
 * Minimal quoting, the way most exports write: only fields with the delimiter, a quote, CR or LF are quoted.
 * @param {string[][]} rows
 * @param {string} delimiter
 * @param {string} eol
 */
function csv(rows, delimiter, eol) {
  const quote = (/** @type {string} */ field) =>
    field.includes(delimiter) || /["\r\n]/.test(field) ? `"${field.replaceAll('"', '""')}"` : field;
  return rows.map((row) => row.map(quote).join(delimiter) + eol).join('');
}

/** @param {string} text */
function utf8(text) {
  return new TextEncoder().encode(text);
}

/** @param {string} text */
function utf16le(text) {
  const bytes = new Uint8Array(text.length * 2);
  for (let i = 0; i < text.length; i++) {
    bytes[2 * i] = text.charCodeAt(i) & 0xff;
    bytes[2 * i + 1] = text.charCodeAt(i) >> 8;
  }
  return bytes;
}

/** A ZIP signature followed by fixed pseudo-random bytes. */
function fakeZip() {
  const bytes = new Uint8Array(256);
  bytes.set([0x50, 0x4b, 0x03, 0x04]);
  let seed = 0x2545f491;
  for (let i = 4; i < bytes.length; i++) {
    seed = (Math.imul(seed, 1103515245) + 12345) >>> 0;
    bytes[i] = seed >>> 24;
  }
  return bytes;
}
